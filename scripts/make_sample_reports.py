"""Write three example reports (confident, uncertain, no pattern) to docs/sample_reports.md."""
import numpy as np

from src.classifier.predict import get_classifier
from src.config import DATA_DIR, PROJECT_ROOT
from src.rag.retriever import get_retriever
from src.report.writer import write_report

CASES = [
    ("Confident defect", lambda p: not p["uncertain"] and p["label"] not in ("none",)),
    ("Uncertain prediction", lambda p: p["uncertain"]),
    ("No defect pattern", lambda p: not p["uncertain"] and p["label"] == "none"),
]


def main() -> None:
    data = np.load(DATA_DIR / "processed" / "wafers_64.npz")
    X, y = data["X_test"], data["y_test"]
    clf, retriever = get_classifier(), get_retriever()
    preds = clf.predict_batch(list(X[:500]))

    sections = ["# Sample WaferLens reports\n",
                "Generated from real WM-811K test wafers. "
                "Pattern and confidence come from the CNN; text is written by the LLM "
                "using only the retrieved knowledge-base notes.\n"]

    for title, matches in CASES:
        i = next(idx for idx, p in enumerate(preds) if matches(p))
        report = write_report(preds[i], retriever.retrieve_for_prediction(preds[i]))
        sections += [
            f"## {title}",
            f"*Test wafer #{i} | true label: {clf.classes[y[i]]} | "
            f"generated by: {report.generated_by}*\n",
            report.markdown,
            "\n---\n",
        ]

    out = PROJECT_ROOT / "results" / "sample_reports.md"
    out.write_text("\n".join(sections), encoding="utf-8")
    print(f"Wrote {out.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()