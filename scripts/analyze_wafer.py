"""Analyse a wafer map from the terminal.

Examples:
  python -m scripts.analyze_wafer --test-index 4
  python -m scripts.analyze_wafer --file samples/edge-ring.npy --json results/edge_ring.json
  python -m scripts.analyze_wafer --export-samples
"""
import argparse
import json
import logging
from pathlib import Path

import numpy as np

from src.config import DATA_DIR, LABEL_MAP_PATH, PROJECT_ROOT

SAMPLES_DIR = PROJECT_ROOT / "samples"


def load_test_set():
    data = np.load(DATA_DIR / "processed" / "wafers_64.npz")
    return data["X_test"], data["y_test"]


def export_samples() -> None:
    """Save one confidently classified test wafer per class to samples/<class>.npy."""
    from src.classifier.predict import get_classifier

    X, y = load_test_set()
    clf = get_classifier()
    preds = clf.predict_batch(list(X))
    SAMPLES_DIR.mkdir(exist_ok=True)

    for c, name in enumerate(clf.classes):
        candidates = [i for i in np.where(y == c)[0]
                      if preds[i]["label"] == name and not preds[i]["uncertain"]]
        i = candidates[0] if candidates else int(np.where(y == c)[0][0])
        path = SAMPLES_DIR / f"{name.lower()}.npy"
        np.save(path, X[i].astype(np.uint8))
        print(f"  {path.relative_to(PROJECT_ROOT)}  (test wafer #{i})")


def main() -> None:
    parser = argparse.ArgumentParser(description="Analyse a wafer map with WaferLens.")
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--file", type=Path, help="Path to a 2D .npy wafer map (values 0/1/2)")
    source.add_argument("--test-index", type=int, help="Index of a wafer in the test set")
    source.add_argument("--export-samples", action="store_true", help="Write samples/<class>.npy")
    parser.add_argument("--json", type=Path, help="Also save the full result as JSON")
    args = parser.parse_args()

    logging.basicConfig(level=logging.WARNING)

    if args.export_samples:
        export_samples()
        return

    from src.pipeline import get_pipeline

    if args.file:
        wafer = np.load(args.file)
        true_label = None
    else:
        X, y = load_test_set()
        wafer = X[args.test_index]
        true_label = json.loads(LABEL_MAP_PATH.read_text())[int(y[args.test_index])]

    result = get_pipeline().analyze(wafer)

    if true_label:
        print(f"(True label: {true_label})\n")
    print(result.report_markdown)
    print(f"\nGenerated by: {result.generated_by}   Timings (ms): {result.timings_ms}")
    for w in result.warnings:
        print(f"WARNING: {w}")

    if args.json:
        args.json.write_text(json.dumps(result.to_dict(), indent=2), encoding="utf-8")
        print(f"Saved {args.json}")


if __name__ == "__main__":
    main()